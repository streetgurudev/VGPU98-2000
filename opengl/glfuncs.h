/*
 * OpenGL 1.1's 336 functions, in the order of the table the ICD
 * (vgpu98gl.dll) gives Windows'
 * opengl32.dll. DrvSetContext returns that table: a count, then one pointer
 * per function, glNewList first and glPushClientAttrib last. opengl32.dll's
 * own gl* exports call through it by position, so the order is fixed: an
 * entry out of place sends a program's calls to the wrong function.
 *
 * One line per function:
 *     GLF(index, return type, name, (parameters), (arguments), stack bytes)
 * the name without its "gl". The stack bytes are what the stdcall function's
 * arguments take on the x86 stack, popped by the function as it returns: 8
 * for a GLdouble or GLclampd, 4 for anything else (pointers, and the byte and
 * short types, which are widened to a dword when pushed). They are the n of
 * a stdcall symbol's name@n.
 *
 * The facts come from the community loaders, read for facts: the order, the
 * types and the stack bytes from ReactOS's opengl32 (its function list and
 * its dispatch table's declaration, which agree), the stack bytes checked
 * against the export lists of ReactOS's and Wine's opengl32.dll, and the
 * types against the XP DDK's gl.h (read for facts). glPixelMap's size is
 * GLsizei, as the DDK and Wine have it (ReactOS's list says GLint, the same
 * 4 bytes). The parameter names are ours.
 *
 * Use: define GLF(index, ret, name, params, args, stack), then include this
 * file, which undefines GLF at its end. It has no include guard around the
 * list, so it can be included as often as a table needs; glenum.h gives the
 * types.
 *
 * Copyright 2026 VGPU98 Project contributors
 * SPDX-License-Identifier: GPL-2.0-or-later
 */


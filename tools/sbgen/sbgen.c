/*
 * sbgen: writes the shared block's layout (driver32/shared.h) as a NASM
 * include for the 16-bit display driver, so both halves of the driver use one
 * definition. The block has fixed-width fields only, so the host compiler's
 * offsets are the 32-bit DLL's.
 *
 *   sbgen OUTPUT
 *
 * Copyright 2026 VGPU98 Project contributors
 * SPDX-License-Identifier: GPL-2.0-or-later
 */
#include <stdio.h>
#include <stdlib.h>

#include "shared.h"
#include "util.h"

static FILE *out;

static void
equ(const char *name, unsigned long value)
{
    fprintf(out, "%-32s equ 0x%lX\n", name, value);
}

#define F(prefix, type, field) equ(prefix #field, (unsigned long) offsetof(type, field))

int
main(int argc, char **argv)
{
    set_progname("sbgen");
    if (argc != 2)
        die("usage: sbgen OUTPUT");
    out = fopen(argv[1], "wb");
    if (!out)
        die("cannot write %s", argv[1]);

    fprintf(out, "; Generated by sbgen from driver32/shared.h. Do not edit.\n\n");

    fprintf(out, "; vgpu98_shared_t\n");
    equ("SB_MAGIC", SB_MAGIC);
    equ("SB_VERSION", SB_VERSION);
    equ("SB_SIZE", sizeof(vgpu98_shared_t));
    equ("SB_MAX_MODES", SB_MAX_MODES);
    equ("SB_DRIVER_OWNER", SB_DRIVER_OWNER);
    equ("SB_RING_SIZE", SB_RING_SIZE);
    F("SB_", vgpu98_shared_t, magic);
    F("SB_", vgpu98_shared_t, version);
    F("SB_", vgpu98_shared_t, size);
    F("SB_", vgpu98_shared_t, fb_linear);
    F("SB_", vgpu98_shared_t, regs_linear);
    F("SB_", vgpu98_shared_t, vram_size);
    F("SB_", vgpu98_shared_t, reserve_base);
    F("SB_", vgpu98_shared_t, mode_width);
    F("SB_", vgpu98_shared_t, mode_height);
    F("SB_", vgpu98_shared_t, mode_bpp);
    F("SB_", vgpu98_shared_t, mode_pitch);
    F("SB_", vgpu98_shared_t, mode_refresh);
    F("SB_", vgpu98_shared_t, mode_serial);
    F("SB_", vgpu98_shared_t, lock);
    F("SB_", vgpu98_shared_t, lock_owner);
    F("SB_", vgpu98_shared_t, lock_time);
    F("SB_", vgpu98_shared_t, fence_issued);
    F("SB_", vgpu98_shared_t, fence_flip);
    F("SB_", vgpu98_shared_t, flip_start);
    F("SB_", vgpu98_shared_t, ring_tail);
    F("SB_", vgpu98_shared_t, state_epoch);
    F("SB_", vgpu98_shared_t, state_owner);
    F("SB_", vgpu98_shared_t, dll_ready);
    F("SB_", vgpu98_shared_t, dll_hinstance);
    F("SB_", vgpu98_shared_t, profile);
    F("SB_", vgpu98_shared_t, hal_flags);
    F("SB_", vgpu98_shared_t, halinfo);
    F("SB_", vgpu98_shared_t, cb_dd);
    F("SB_", vgpu98_shared_t, cb_surf);
    F("SB_", vgpu98_shared_t, cb_pal);
    F("SB_", vgpu98_shared_t, cb_exebuf);
    F("SB_", vgpu98_shared_t, heap);
    F("SB_", vgpu98_shared_t, num_modes);
    F("SB_", vgpu98_shared_t, modes);

    fprintf(out, "\n; DDHALINFO\n");
    equ("HI_SIZE", sizeof(DDHALINFO));
    F("HI_", DDHALINFO, dwSize);
    F("HI_", DDHALINFO, lpDDCallbacks);
    F("HI_", DDHALINFO, lpDDSurfaceCallbacks);
    F("HI_", DDHALINFO, lpDDPaletteCallbacks);
    F("HI_", DDHALINFO, vmiData);
    F("HI_", DDHALINFO, ddCaps);
    F("HI_", DDHALINFO, dwMonitorFrequency);
    F("HI_", DDHALINFO, GetDriverInfo);
    F("HI_", DDHALINFO, dwModeIndex);
    F("HI_", DDHALINFO, lpdwFourCC);
    F("HI_", DDHALINFO, dwNumModes);
    F("HI_", DDHALINFO, lpModeInfo);
    F("HI_", DDHALINFO, dwFlags);
    F("HI_", DDHALINFO, lpPDevice);
    F("HI_", DDHALINFO, hInstance);
    F("HI_", DDHALINFO, lpD3DGlobalDriverData);
    F("HI_", DDHALINFO, lpD3DHALCallbacks);
    F("HI_", DDHALINFO, lpDDExeBufCallbacks);
    equ("DDHALINFO_ISPRIMARYDISPLAY", DDHALINFO_ISPRIMARYDISPLAY);
    equ("DDHALINFO_GETDRIVERINFOSET", DDHALINFO_GETDRIVERINFOSET);

    fprintf(out, "\n; VIDMEMINFO\n");
    F("VMI_", VIDMEMINFO, fpPrimary);
    F("VMI_", VIDMEMINFO, dwFlags);
    F("VMI_", VIDMEMINFO, dwDisplayWidth);
    F("VMI_", VIDMEMINFO, dwDisplayHeight);
    F("VMI_", VIDMEMINFO, lDisplayPitch);
    F("VMI_", VIDMEMINFO, ddpfDisplay);
    F("VMI_", VIDMEMINFO, dwOffscreenAlign);
    F("VMI_", VIDMEMINFO, dwOverlayAlign);
    F("VMI_", VIDMEMINFO, dwTextureAlign);
    F("VMI_", VIDMEMINFO, dwZBufferAlign);
    F("VMI_", VIDMEMINFO, dwAlphaAlign);
    F("VMI_", VIDMEMINFO, dwNumHeaps);
    F("VMI_", VIDMEMINFO, pvmList);

    fprintf(out, "\n; DDPIXELFORMAT\n");
    equ("PF_SIZE", sizeof(DDPIXELFORMAT));
    F("PF_", DDPIXELFORMAT, dwSize);
    F("PF_", DDPIXELFORMAT, dwFlags);
    F("PF_", DDPIXELFORMAT, dwFourCC);
    F("PF_", DDPIXELFORMAT, dwRGBBitCount);
    F("PF_", DDPIXELFORMAT, dwRBitMask);
    F("PF_", DDPIXELFORMAT, dwGBitMask);
    F("PF_", DDPIXELFORMAT, dwBBitMask);
    F("PF_", DDPIXELFORMAT, dwRGBAlphaBitMask);
    equ("DDPF_RGB", DDPF_RGB);
    equ("DDPF_PALETTEINDEXED8", DDPF_PALETTEINDEXED8);

    fprintf(out, "\n; VIDMEM\n");
    equ("VM_SIZE", sizeof(VIDMEM));
    F("VM_", VIDMEM, dwFlags);
    F("VM_", VIDMEM, fpStart);
    F("VM_", VIDMEM, fpEnd);
    F("VM_", VIDMEM, ddsCaps);
    F("VM_", VIDMEM, ddsCapsAlt);
    F("VM_", VIDMEM, lpHeap);
    equ("VIDMEM_ISLINEAR", VIDMEM_ISLINEAR);

    fprintf(out, "\n; DDHALMODEINFO\n");
    equ("MI_SIZE", sizeof(DDHALMODEINFO));
    F("MI_", DDHALMODEINFO, dwWidth);
    F("MI_", DDHALMODEINFO, dwHeight);
    F("MI_", DDHALMODEINFO, lPitch);
    F("MI_", DDHALMODEINFO, dwBPP);
    F("MI_", DDHALMODEINFO, wFlags);
    F("MI_", DDHALMODEINFO, wRefreshRate);
    F("MI_", DDHALMODEINFO, dwRBitMask);
    F("MI_", DDHALMODEINFO, dwGBitMask);
    F("MI_", DDHALMODEINFO, dwBBitMask);
    F("MI_", DDHALMODEINFO, dwAlphaBitMask);
    equ("DDMODEINFO_PALETTIZED", DDMODEINFO_PALETTIZED);

    fprintf(out, "\n; Callback tables\n");
    equ("CBDD_SIZE", sizeof(DDHAL_DDCALLBACKS));
    equ("CBSURF_SIZE", sizeof(DDHAL_DDSURFACECALLBACKS));
    equ("CBPAL_SIZE", sizeof(DDHAL_DDPALETTECALLBACKS));
    equ("CBEXE_SIZE", sizeof(DDHAL_DDEXEBUFCALLBACKS));
    F("CBDD_", DDHAL_DDCALLBACKS, dwSize);
    F("CBDD_", DDHAL_DDCALLBACKS, dwFlags);
    F("CBDD_", DDHAL_DDCALLBACKS, DestroyDriver);
    F("CBSURF_", DDHAL_DDSURFACECALLBACKS, dwSize);
    F("CBPAL_", DDHAL_DDPALETTECALLBACKS, dwSize);
    F("CBEXE_", DDHAL_DDEXEBUFCALLBACKS, dwSize);
    F("CBEXE_", DDHAL_DDEXEBUFCALLBACKS, dwFlags);

    fprintf(out, "\n; DDCORECAPS\n");
    equ("CAPS_SIZE", sizeof(DDCORECAPS));
    F("CAPS_", DDCORECAPS, dwSize);

    fprintf(out, "\n; The escape for the Glide DLLs: vgpu98_escquery_t in, vgpu98_escinfo_t out\n");
    equ("VGPU98_ESC_INFO", VGPU98_ESC_INFO);
    equ("ESC_INFO_MAGIC", ESC_INFO_MAGIC);
    F("EQ_", vgpu98_escquery_t, magic);
    F("EQ_", vgpu98_escquery_t, out_size);
    equ("EI_SIZE", sizeof(vgpu98_escinfo_t));
    F("EI_", vgpu98_escinfo_t, magic);
    F("EI_", vgpu98_escinfo_t, size);
    F("EI_", vgpu98_escinfo_t, shared_linear);
    F("EI_", vgpu98_escinfo_t, sb_version);
    F("EI_", vgpu98_escinfo_t, stamp);

    fprintf(out, "\n; The escape for the OpenGL ICD: vgpu98_escaccess_t in\n");
    equ("VGPU98_ESC_ACCESS", VGPU98_ESC_ACCESS);
    F("EA_", vgpu98_escaccess_t, begin);
    F("EA_", vgpu98_escaccess_t, left);
    F("EA_", vgpu98_escaccess_t, top);
    F("EA_", vgpu98_escaccess_t, right);
    F("EA_", vgpu98_escaccess_t, bottom);

    if (fclose(out) != 0)
        die("cannot write %s", argv[1]);
    return 0;
}
